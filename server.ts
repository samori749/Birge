app.post('/api/ai/chat', async (req, res) => {
  try {
    const { prompt, category, language, context } = req.body;
    if (!prompt) {
      return res.status(400).json({ error: 'Prompt is required' });
    }

    if (!ai) {
      return res.json({
        text: getSmartFallbackResponse(prompt, category, language || 'ky'),
        model: 'birge-smart-rules',
      });
    }

    const langDirective = (language === 'ky' || language === 'kg')
      ? 'Жоопту толугу менен кыргыз тилинде бер.'
      : 'Ответь подробно на русском языке.';

    const userPromptWithContext = `[Категория: ${category || 'Общее'}]
[Тил/Язык: ${language || 'ky'}]
${context ? `[Контекст: ${context}]\n` : ''}
Колдонуучунун суроосу / Запрос пользователя:
${prompt}

${langDirective}`;

    const response = await ai.models.generateContent({
      model: 'gemini-3.8-flash',
      contents: userPromptWithContext,
      config: {
        systemInstruction: SYSTEM_INSTRUCTION,
        temperature: 0.7,
      },
    });

    const reply = response.text || '';
    return res.json({
      text: reply,
      model: 'gemini-3.8-flash',
    });
  } catch (err: any) {
    console.error('Gemini API error, falling back to smart guide:', err);
    const { prompt, category, language } = req.body;
    return res.json({
      text: getSmartFallbackResponse(prompt, category, language || 'ky'),
      model: 'birge-smart-rules-fallback',
      warning: 'Ответ сформирован из верифицированной базы знаний Бирге KG',
    });
  }
});

